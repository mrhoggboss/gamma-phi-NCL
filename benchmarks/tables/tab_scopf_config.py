#!/usr/bin/env python3
"""tab_scopf_config — the SCOPF benchmark's settings that differ from the other GPU suites
(manuscript float tab:scopf-config), read from the configuration file the run itself wrote
(<resdir>/config_scopf__<tag>.txt, benchmarks/gpu.jl), so the table cannot drift from the harness.

Usage: python3 benchmarks/tables/tab_scopf_config.py <resdir> [--tag=r1] [--out=<dir>]
"""
import glob, math, os, re, sys
from common import DEFAULT_OUT, write

# Caption: the manuscript's (overleaf_upload/tables/tab_scopf_config.tex), verbatim (captions are Yifan's).
# TODO(caption, stale items to revise):
#   - it describes the tolerance-1e-5 suite: tau_relax = 1e-5 ("at tau_relax = 0 ... no interior-point method can
#     make progress") and an inner s_max of 1e20 "ours rather than the benchmark's". The run now has tau_relax = 0
#     (the problem (P)), tolerance 1e-8 and MadNLP's default s_max = 100, so neither entry is in the rows below.
#   - the rationale column below is not Yifan's text; it needs his wording.
CAPTION = ("Configuration exceptions for the security-constrained OPF benchmark. These are\n"
           "properties of the benchmark rather than of any one solver, and are applied identically to\n"
           "every configuration compared on it. The complementarity relaxation $\\tau_{\\mathrm{relax}}$\n"
           "is part of the problem formulation: at $\\tau_{\\mathrm{relax}}=0$ the feasible set has empty\n"
           "interior and no interior-point method can make progress. The inner $s_{\\max}$ is the one\n"
           "entry that is ours rather than the benchmark's --- the reference implementation uses\n"
           "MadNLP's default of $100$, and we note the difference rather than silently adopting it.")


def sci(x):
    x = float(x)
    if x == 0:
        return "$0$"
    e = round(math.log10(abs(x)))
    if abs(x - 10.0 ** e) > 1e-12 * abs(x):
        return f"${x:g}$"
    return "$1$" if e == 0 else f"$10^{{{e}}}$"


def field(text, key):
    m = re.search(r"\b" + key + r"\s*=\s*([^,\s)]+)", text)
    if not m:
        raise SystemExit(f"{key} not found in the run's configuration file")
    return m.group(1)


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    tag = opt.get("tag", "r1")
    path = os.path.join(pos[0], f"config_scopf__{tag}.txt")
    if not os.path.isfile(path):
        # one echo per configuration (config_scopf__<config>__<tag>.txt, one run per configuration): the suite's
        # settings read here are the same in all of them; check that and use the first
        cands = sorted(glob.glob(os.path.join(pos[0], f"config_scopf__*__{tag}.txt")))
        if not cands:
            raise SystemExit(f"no config_scopf__{tag}.txt or config_scopf__<config>__{tag}.txt in {pos[0]}")
        keys = ("max_iter", "tau_relax", "scale_obj", "scale_cc", "richardson_tol", "richardson_max_iter")
        vals = {c: tuple(field(open(c).read(), k) for k in keys) for c in cands}
        if len(set(vals.values())) != 1:
            raise SystemExit(f"the configuration echoes disagree on the suite settings: {vals}")
        path = cands[0]
    text = open(path).read()
    rows = [
        ("interior-point iteration limit", f"${field(text, 'max_iter')}$", "1000 on the other GPU suites"),
        ("$\\tau_{\\mathrm{relax}}$", sci(field(text, "tau_relax")), "complementarity product of the problem"),
        ("objective scaling", sci(field(text, "scale_obj")), "as in the reference benchmark"),
        ("complementarity-row scaling", sci(field(text, "scale_cc")), "as in the reference benchmark"),
        ("Richardson refinement tolerance", sci(field(text, "richardson_tol")), "as in the reference benchmark"),
        ("Richardson refinement steps", f"${field(text, 'richardson_max_iter')}$", "as in the reference benchmark"),
    ]
    if "cudss_pivot_epsilon" in text:
        rows.append(("cuDSS pivot perturbation", sci(field(text, "cudss_pivot_epsilon")), "as in the reference benchmark"))
    for r in rows:
        print(f"  {r[0]:<36} {r[1]:<10} {r[2]}")
    T = ["% GENERATED by benchmarks/tables/tab_scopf_config.py -- do not hand-edit.", "% REQUIRES: booktabs",
         f"% source: {os.path.basename(path)}",
         "\\begin{table}[t]\\centering\\small", "\\caption{" + CAPTION + "}", "\\label{tab:scopf-config}",
         "\\begin{tabular}{lll}\\toprule", "parameter & value & rationale \\\\\\midrule"]
    T += [f"{a} & {b} & {c} \\\\" for a, b, c in rows]
    T += ["\\bottomrule\\end{tabular}\\end{table}"]
    write(opt.get("out", DEFAULT_OUT), "tab_scopf_config.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
