#!/usr/bin/env python3
"""tab_gpu_scopf_pglib — the 18 protocol SCOPF instances, per instance: a table of earlier manuscript versions, NOT a
float and not emitted (an unreported extra, runnable by hand; kept for instance_names, imported by the unreported extra
tab_scopf_pglib_appendix.py; its parts and tex_name are common.pglib_scopf_parts and common.pglib_scopf_tex); protocol:
benchmarks/scopf_protocol/README.md. 3 networks (case500_goc, case588_sdet, case793_goc) x K in {4, 8, 16}
contingencies x two screening orders (A, B).

Layout, roster order and scoring of tab_gpu_scopf.py. Reads <resdir>/scopf_pglib__<config>__<tag>.csv (rows copied from
the WO-69 pilot runs, benchmarks/results/paper/scopf_pglib/SOURCE.txt). With several repetitions, a configuration
solves an instance when a strict majority of its repetitions does, and the cell shows the medians of the
interior-point iterations and factorizations over the succeeding repetitions; a dash is a non-solve. Footer: solved
count and the geometric mean of factorizations over the solved set. LiftedKKT (MadNLP) has no constraint-violation
test: its solves count only if the returned point's raw violation (pr_res) is within the run's constr_viol_tol
(post-hoc guard; the unguarded count in parentheses when it differs). Instances are printed as network, order and K
(\\texttt{500\\_goc~A}@8), ordered by bus count, network, order, K.

Usage: python3 benchmarks/tables/tab_gpu_scopf_pglib.py <resdir> [--cvtol=<t>] [--out=<dir>]
"""
import sys
from common import (DEFAULT_OUT, PGLIB_SCOPF_PAT, assert_no_tokens, find, fmt, gm, group_header, majority, ordered,
                    pglib_scopf_parts, pglib_scopf_tex, read_cvtol, read_rows, write)

# Unreported extra (an earlier manuscript layout); not a float, no caption will be written.
CAPTION = ("The protocol security-constrained complementarity problems generated from PGLIB, per "
           "instance (network, screening order, number of contingencies $K$), majority of three repetitions. For each "
           "solve, the entry is the median interior-point iteration count and factorization count over the "
           "repetitions that succeed; a dash is a non-solve.")
# the instance-name helpers, re-exported from common
PAT, parts, tex_name = PGLIB_SCOPF_PAT, pglib_scopf_parts, pglib_scopf_tex


def instance_names(data, configs):
    names = set()
    for c in configs:
        for rows in data[c].values():
            names |= set(rows)
    names = sorted(names, key=parts)
    if len(names) != 18:
        print(f"  NOTE: {len(names)} instances in the results (the protocol set has 18)")
    return names


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    files = find(pos[0], r"scopf_pglib__(.+?)__(.+?)\.csv")
    configs = ordered(files)
    cvtol = read_cvtol(pos[0], opt)
    data = {c: {t: read_rows(files[c][t], "instance") for t in files[c]} for c in configs}
    names = instance_names(data, configs)
    k = len(configs)
    T = ["% GENERATED by benchmarks/tables/tab_gpu_scopf_pglib.py -- do not hand-edit.", "% REQUIRES: booktabs",
         "\\begin{table}[tbp]\\centering\\small\\setlength{\\tabcolsep}{3pt}", "\\caption{" + CAPTION + "}", "\\label{tab:gpu-scopf-pglib}",
         "\\begin{tabular}{l" + "rr" * k + "}\\toprule"] + group_header(configs, 2, 1) + [
         "instance & " + " & ".join("iter.\\ & fact." for _ in configs) + " \\\\\\midrule"]
    summ = {c: [] for c in configs}
    raw = {c: sum(1 for n in names if majority(data[c], n)[0]) for c in configs}
    for n in names:
        cells = []
        for c in configs:
            ok, nf, it = majority(data[c], n, c, cvtol)
            if ok:
                summ[c].append(nf)
                cells += [f"{it:.0f}", f"{nf:.0f}"]
            else:
                cells += ["---", "---"]
        T.append(f"{tex_name(n)} & " + " & ".join(cells) + " \\\\")
    T.append("\\midrule solved & " + " & ".join(
        f"\\multicolumn{{2}}{{c}}{{{len(summ[c])}/{len(names)}" + (f" ({raw[c]})" if raw[c] != len(summ[c]) else "") + "}"
        for c in configs) + " \\\\")
    T.append("factorizations (geom.\\ mean) & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{fmt(gm(summ[c]))}}}" for c in configs) + " \\\\")
    T.append("\\bottomrule\\end{tabular}\\end{table}")
    for c in configs:
        nrows = {t: len(r) for t, r in sorted(data[c].items())}
        print(f"  {c:<10} solved {len(summ[c])}/{len(names)} (unguarded {raw[c]})  gm fact {gm(summ[c]):.1f}  rows per rep {nrows}")
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_gpu_scopf_pglib.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
