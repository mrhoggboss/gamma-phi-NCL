#!/usr/bin/env python3
"""tab_pglib_appendix — all 66 PGLIB v23.07 cases, one row each (appendix table), for every configuration and
baseline found in the result directory.

Reads <resdir>/opf__<config>__<tag>.csv (benchmarks/gpu.jl). Rows are ordered by bus count (then name). Per
configuration: interior-point iterations and factorizations, with the wall time as an informational column. With
several repetitions an instance is solved when a strict majority of them succeeds, and the cells are the medians
over the succeeding repetitions; a non-solve shows the most frequent status. LiftedKKT (MadNLP) has no
constraint-violation test: its solves count only if the returned point's raw violation (pr_res) is within the run's
constr_viol_tol (post-hoc guard); a solve removed by the guard shows "viol.", and the footer gives the unguarded count
in parentheses. The footer is computed with the same scoring as tab_gpu_opf (benchmarks/tables/common.suite_scores),
over all cases, and is asserted to equal the column sums of the rows above it.

Usage: python3 benchmarks/tables/tab_pglib_appendix.py <resdir> [--cvtol=<t>] [--out=<dir>]
"""
import os, re, statistics, sys
from common import (DEFAULT_OUT, LANDSCAPE_BEGIN, LANDSCAPE_END, LANDSCAPE_REQUIRES, HERE, assert_no_tokens, group_header, find, fmt, gm, majority, majority_status, ordered, success,
                    read_cvtol, read_rows, suite_scores, write)

# TODO(caption): a draft (captions are Yifan's); port his wording verbatim once he writes it.
CAPTION = ("[DRAFT CAPTION] All 66 PGLIB v23.07 instances, ordered by bus count. For each configuration, the "
           "interior-point iterations and factorizations of the solve (with several repetitions: the medians over the "
           "repetitions that succeed, when a strict majority succeeds) and the wall time in seconds, for information; "
           "a non-solve shows its termination status.")
SHORT = {"MAXIMUM_ITERATIONS_EXCEEDED": "iter.\\ limit", "INFEASIBLE_PROBLEM_DETECTED": "infeasible",
         "MAXIMUM_WALLTIME_EXCEEDED": "wall limit", "SOLVED_TO_ACCEPTABLE_LEVEL": "acceptable",
         "VIOLATION": "viol.", "MISSING": "not run", "BUILD_FAILED": "no build"}


def nbus(name):
    m = re.match(r"pglib_opf_case(\d+)", name)
    return int(m[1]) if m else 0


def tex_name(name):
    return "\\texttt{" + name.replace("pglib_opf_", "").replace("_", "\\_") + "}"


def short(st):
    if st.startswith("ERROR"):
        return "error"
    return SHORT.get(st, st.lower().replace("_", " "))


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    cvtol = read_cvtol(pos[0], opt)
    files = find(pos[0], r"opf__(.+?)__(.+?)\.csv")
    configs = ordered(files)
    data = {c: {t: read_rows(files[c][t], "instance") for t in files[c]} for c in configs}
    names = sorted(set().union(*[set(r) for c in configs for r in data[c].values()]), key=lambda n: (nbus(n), n))
    if len(names) != 66:
        print(f"  NOTE: {len(names)} cases in the results (the appendix is meant to cover all 66)")
    for c in configs:
        missing = [n for n in names if any(n not in rows for rows in data[c].values())]
        if missing:
            print(f"  NOTE: {c} has no row for {len(missing)} case(s), shown as 'not run': {missing[:5]}")

    k = len(configs)
    T = ["% GENERATED by benchmarks/tables/tab_pglib_appendix.py -- do not hand-edit.", *LANDSCAPE_REQUIRES, *LANDSCAPE_BEGIN,
         "{\\footnotesize\\setlength{\\tabcolsep}{3pt}",
         "\\begin{longtable}{lr" + "rrr" * k + "}",
         "\\caption{" + CAPTION + "}\\label{tab:pglib-appendix}\\\\"]
    head = ["\\toprule"] + group_header(configs, 3, 2) + [
            "case & buses & " + " & ".join("iter. & fact. & wall" for _ in configs) + " \\\\\\midrule"]
    T += head + ["\\endfirsthead"] + head + ["\\endhead", "\\bottomrule", "\\endfoot"]
    colsum = {c: {"all": 0, "fact": []} for c in configs}
    for n in names:
        cells = []
        for c in configs:
            ok, nf, it = majority(data[c], n, c, cvtol)
            if ok:
                walls = [float(rows[n]["wall"]) for rows in data[c].values()
                         if n in rows and success(rows[n], c, None, cvtol)]
                cells += [f"{it:.0f}", f"{nf:.0f}", f"{statistics.median(walls):.1f}"]
                colsum[c]["all"] += 1; colsum[c]["fact"].append(nf)
            else:
                cells += [f"\\multicolumn{{3}}{{c}}{{\\textit{{{short(majority_status(data[c], n, c, cvtol))}}}}}"]
        T.append(f"{tex_name(n)} & {nbus(n)} & " + " & ".join(cells) + " \\\\")
    # footer with the scoring of tab_gpu_opf, asserted equal to the column sums above
    foot = {}
    for c in configs:
        a = suite_scores(data[c], names, c, cvtol)
        assert len(a["solved"]) == colsum[c]["all"], (c, len(a["solved"]), colsum[c]["all"])
        assert fmt(a["cost"]) == fmt(gm(colsum[c]["fact"]))
        foot[c] = (a,)
        print(f"  {c:<10} solved {len(a['solved'])}/{len(names)} (unguarded {a['n_raw']}), gm fact {a['cost']:.1f}")

    def cnt(s):
        return f"{len(s['solved'])}" + (f" ({s['n_raw']})" if s["n_raw"] != len(s["solved"]) else "")
    T.append("\\midrule")
    T.append(f"solved (all {len(names)}) & & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{cnt(foot[c][0])}}}" for c in configs) + " \\\\")
    T.append("factorizations (geom.\\ mean) & & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{fmt(foot[c][0]['cost'])}}}" for c in configs) + " \\\\")
    T.append("\\end{longtable}}")
    T += LANDSCAPE_END
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_pglib_appendix.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
