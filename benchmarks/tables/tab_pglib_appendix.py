#!/usr/bin/env python3
"""tab_pglib_appendix — all 66 PGLIB v23.07 cases, one row each (appendix table), for every configuration and
baseline found in the result directory.

Reads <resdir>/opf__<config>__<tag>.csv (benchmarks/gpu.jl). Rows are ordered by bus count (then name). Per
configuration one column per repetition (Yifan 2026-11-12: "list the factorizations (when successful) or failure
reason of all three reps"): the factorization count of a repetition that solves, else the reason for the non-solve
as a short italic word (common.rep_cell, common.FAIL_WORD; no iteration, wall-time or median columns). LiftedKKT (MadNLP) has no
constraint-violation test: its solves count only if the returned point's raw violation (pr_res) is within the run's
constr_viol_tol (post-hoc guard). The footer gives the solved count of every repetition, computed with the scoring of
tab_gpu_opf (benchmarks/tables/common.suite_scores) and asserted to equal the count of numeric cells above it.

Usage: python3 benchmarks/tables/tab_pglib_appendix.py <resdir> [--cvtol=<t>] [--out=<dir>]
"""
import re, sys
from common import (DEFAULT_OUT, LANDSCAPE_BEGIN, LANDSCAPE_END, LANDSCAPE_REQUIRES, assert_no_tokens, group_header,
                    find, ordered, read_cvtol, read_rows, rep_cell, suite_scores, write)

# Caption: the manuscript's (Yifan, Overleaf 0eae8ef), verbatim (captions are Yifan's).
CAPTION = ("Detailed results of the solvers on all 66 PGLIB instances, ordered by bus count. For each repetition, we report "
           "either the number of factorizations needed for the successful solve, or the reason for the non-solve.")


def nbus(name):
    m = re.match(r"pglib_opf_case(\d+)", name)
    return int(m[1]) if m else 0


def tex_name(name):
    return "\\texttt{" + name.replace("pglib_opf_", "").replace("_", "\\_") + "}"


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    cvtol = read_cvtol(pos[0], opt)
    files = find(pos[0], r"opf__(.+?)__(.+?)\.csv")
    configs = ordered(files)
    data = {c: {t: read_rows(files[c][t], "instance") for t in files[c]} for c in configs}
    tags = sorted({t for c in configs for t in data[c]})
    assert all(sorted(data[c]) == tags for c in configs), {c: sorted(data[c]) for c in configs}
    names = sorted(set().union(*[set(r) for c in configs for r in data[c].values()]), key=lambda n: (nbus(n), n))
    if len(names) != 66:
        print(f"  NOTE: {len(names)} cases in the results (the appendix is meant to cover all 66)")

    k, m = len(configs), len(tags)
    T = ["% GENERATED by benchmarks/tables/tab_pglib_appendix.py -- do not hand-edit.", *LANDSCAPE_REQUIRES, *LANDSCAPE_BEGIN,
         # \footnotesize, \tabcolsep 2.5pt (the largest size that fits both appendix tables on the landscape text width,
         # 650.4pt: PGLIB 620.6pt, SCOPF 636.6pt; at 3pt the SCOPF table is 4.2pt too wide)
         "{\\footnotesize\\setlength{\\tabcolsep}{2.5pt}",
         "\\begin{longtable}{lr" + "r" * (m * k) + "}",
         "\\caption{" + CAPTION + "}\\label{tab:pglib-appendix}\\\\"]
    head = ["\\toprule"] + group_header(configs, m, 2) + [
            "case & buses & " + " & ".join(" & ".join(str(i + 1) for i in range(m)) for _ in configs) + " \\\\\\midrule"]
    T += head + ["\\endfirsthead"] + head + ["\\endhead", "\\bottomrule", "\\endfoot"]
    nsol = {(c, t): 0 for c in configs for t in tags}
    for n in names:
        cells = []
        for c in configs:
            for t in tags:
                x = rep_cell(data[c][t].get(n), c, cvtol)
                nsol[(c, t)] += x.isdigit()
                cells.append(x)
        T.append(f"{tex_name(n)} & {nbus(n)} & " + " & ".join(cells) + " \\\\")
    for c in configs:
        a = suite_scores(data[c], names, c, cvtol)
        assert all(a["per_rep"][t][0] == nsol[(c, t)] for t in tags), (c, a["per_rep"], nsol)
        print(f"  {c:<10} solved per repetition {[nsol[(c, t)] for t in tags]} of {len(names)}")
    T.append("\\midrule")
    T.append(f"solved (of {len(names)}) & & " + " & ".join(str(nsol[(c, t)]) for c in configs for t in tags) + " \\\\")
    T.append("\\end{longtable}}")
    T += LANDSCAPE_END
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_pglib_appendix.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
