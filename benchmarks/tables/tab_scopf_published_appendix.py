#!/usr/bin/env python3
"""tab_scopf_published_appendix — the SCOPF instances of case_ACTIVSg500, case1354pegase and case_ACTIVSg2000 run on the
contingency lists as published by the reference benchmark (benchmarks/instances/scopf_contingencies_published.jl), one
row each: the runs the paper's protocol lists replaced (Yifan 2026-11-13), kept "for reference". NOT a float of the
manuscript yet (not in SUITES; `emit.sh scopf_published` emits it; reproduce.sh does not compare it).

Reads <resdir>/scopf_published__<config>__<tag>.csv (benchmarks/results/paper/scopf_published/: the 12 instances whose
list changed, ACTIVSg500 K = 8 ... 100, 1354pegase K = 8, 16, 32, ACTIVSg2000 K = 8, 16). With --from=<scopf resdir>
--plus=<instance,...> the listed instances are added from the reference-network results (e.g. case_ACTIVSg500_nK4,
whose list is the same under both: the first 4 outages agree). Layout and scoring of tab_scopf_all_appendix: rows in the
order of the reference networks, K increasing; buses and the number of variables, then per configuration one column per
repetition, the factorization count of a repetition that solves or the reason for the non-solve (common.rep_cell,
common.FAIL_WORD); footer: the solved count of every repetition, and the geometric mean over the majority-solved
instances of the median factorization count of the succeeding repetitions (common.suite_scores, asserted against a
recomputation from the rows). LiftedKKT within the run's constr_viol_tol (post-hoc guard).

Usage: python3 benchmarks/tables/tab_scopf_published_appendix.py <resdir> [--from=<scopf resdir> --plus=<a,b,...>]
         [--cvtol=<t>] [--out=<dir>]
"""
import statistics, sys
from common import (DEFAULT_OUT, LANDSCAPE_BEGIN, LANDSCAPE_END, LANDSCAPE_REQUIRES, assert_no_tokens, find, fmt, gm,
                    group_header, ordered, read_cvtol, read_rows, rep_cell, success, suite_scores, write)
from tab_gpu_scopf_all import buses, key, tex

# TODO(caption): a placeholder (captions are Yifan's); port his wording verbatim once he writes it.
CAPTION = ("[DRAFT CAPTION] The instances of three reference networks run on the contingency lists as published by the "
           "reference benchmark, which the protocol lists replace in the main results. For each repetition, we report "
           "either the number of factorizations needed for the successful solve, or the reason for the non-solve.")


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    cvtol = read_cvtol(pos[0], opt)
    files = find(pos[0], r"scopf_published__(.+?)__(.+?)\.csv")
    configs = ordered(files)
    data = {c: {t: read_rows(files[c][t], "instance") for t in files[c]} for c in configs}
    plus = [p for p in opt.get("plus", "").split(",") if p]
    if plus:
        extra = find(opt["from"], r"scopf__(.+?)__(.+?)\.csv")
        for c in configs:
            assert sorted(extra[c]) == sorted(files[c]), (c, sorted(extra[c]), sorted(files[c]))
            for t in files[c]:
                rows = read_rows(extra[c][t], "instance")
                for n in plus:
                    assert n not in data[c][t], n
                    data[c][t][n] = rows[n]
    tags = sorted({t for c in configs for t in data[c]})
    assert all(sorted(data[c]) == tags for c in configs), {c: sorted(data[c]) for c in configs}
    names = sorted({n for c in configs for rows in data[c].values() for n in rows}, key=key)
    nvar = {}
    for c in configs:
        for rows in data[c].values():
            for n, r in rows.items():
                assert nvar.setdefault(n, r["nvar"]) == r["nvar"], (n, c, nvar[n], r["nvar"])

    k, m = len(configs), len(tags)
    T = ["% GENERATED by benchmarks/tables/tab_scopf_published_appendix.py -- do not hand-edit.", *LANDSCAPE_REQUIRES,
         *LANDSCAPE_BEGIN,
         "{\\footnotesize\\setlength{\\tabcolsep}{2.5pt}",   # the size and separation of tab_scopf_all_appendix
         "\\begin{longtable}{lrr" + "r" * (m * k) + "}",
         "\\caption{" + CAPTION + "}\\label{tab:scopf-published-appendix}\\\\"]
    head = ["\\toprule"] + group_header(configs, m, 3) + [
            "instance & buses & $n_{\\mathrm{var}}$ & " + " & ".join(" & ".join(str(i + 1) for i in range(m)) for _ in configs)
            + " \\\\\\midrule"]
    T += head + ["\\endfirsthead"] + head + ["\\endhead", "\\bottomrule", "\\endfoot"]
    nsol = {(c, t): 0 for c in configs for t in tags}
    for n in names:
        cells = []
        for c in configs:
            for t in tags:
                x = rep_cell(data[c][t].get(n), c, cvtol)
                nsol[(c, t)] += x.isdigit()
                cells.append(x)
        T.append(f"{tex(n)} & {buses(n)} & {nvar[n]} & " + " & ".join(cells) + " \\\\")
    cost = {}
    for c in configs:
        a = suite_scores(data[c], names, c, cvtol)
        assert all(a["per_rep"][t][0] == nsol[(c, t)] for t in tags), (c, a["per_rep"], nsol)
        med = [statistics.median(float(data[c][t][n]["nfact"]) for t in tags if success(data[c][t].get(n), c, None, cvtol))
               for n in names if a["majority"][n][0]]
        assert fmt(gm(med)) == fmt(a["cost"]), (c, gm(med), a["cost"])
        cost[c] = a["cost"]
        print(f"  {c:<10} solved per repetition {[nsol[(c, t)] for t in tags]} of {len(names)}, "
              f"majority {len(a['solved'])}, gm fact {fmt(a['cost'])}")
    T.append("\\midrule")
    T.append(f"\\multicolumn{{3}}{{l}}{{solved (of {len(names)})}} & " + " & ".join(str(nsol[(c, t)]) for c in configs for t in tags)
             + " \\\\")
    T.append("\\multicolumn{3}{l}{factorizations (geom.\\ mean)} & " + " & ".join(
        f"\\multicolumn{{{m}}}{{c}}{{{fmt(cost[c])}}}" for c in configs) + " \\\\")
    T.append("\\end{longtable}}")
    T += LANDSCAPE_END
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_scopf_published_appendix.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
