#!/usr/bin/env python3
"""tab_scopf_pglib_appendix — the 18 protocol SCOPF instances (see tab_gpu_scopf_pglib), one row each (appendix
table), for every configuration of the paper roster found in the result directory; the layout of tab_pglib_appendix,
with per-repetition statuses (common.letter).

Reads <resdir>/scopf_pglib__<config>__<tag>.csv. Rows ordered by bus count, network, order, K; columns: buses and the
number of variables, then per configuration the interior-point iterations and factorizations and the status of every
repetition (no wall-time column: Yifan 2026-11-12; S solved, M iteration limit, I infeasible, W wall-time
limit, A acceptable level, V solve removed by the post-hoc guard, E error, - not run). With several repetitions an
instance is solved when a strict majority of them succeeds, and the cells are the medians over the succeeding
repetitions; a non-solve shows the most frequent status. LiftedKKT (MadNLP) has no constraint-violation test: its
solves count only if the returned point's raw violation (pr_res) is within the run's constr_viol_tol (post-hoc guard).
The footer is computed with the scoring of the other GPU tables (benchmarks/tables/common.suite_scores) and is asserted
to equal the column sums of the rows above it.

Usage: python3 benchmarks/tables/tab_scopf_pglib_appendix.py <resdir> [--cvtol=<t>] [--out=<dir>]
"""
import sys
from common import (DEFAULT_OUT, LANDSCAPE_BEGIN, LANDSCAPE_END, LANDSCAPE_REQUIRES, assert_no_tokens, group_header, find, fmt, gm, letter, majority, majority_status, ordered, read_cvtol,
                    read_rows, short, suite_scores, write)
from tab_gpu_scopf_pglib import instance_names, parts, tex_name

# TODO(caption): a draft (captions are Yifan's); port his wording verbatim once he writes it.
CAPTION = ("[DRAFT CAPTION] The 18 protocol security-constrained complementarity problems generated from PGLIB (network, "
           "screening order, number of contingencies $K$). For each configuration, the interior-point iterations and "
           "factorizations of the solve (the medians over the repetitions that succeed, when a strict majority of the "
           "three succeeds), and the status of each repetition; a non-solve shows its most frequent termination status.")


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    cvtol = read_cvtol(pos[0], opt)
    files = find(pos[0], r"scopf_pglib__(.+?)__(.+?)\.csv")
    configs = ordered(files)
    data = {c: {t: read_rows(files[c][t], "instance") for t in files[c]} for c in configs}
    names = instance_names(data, configs)
    nvar = {}
    for c in configs:
        for rows in data[c].values():
            for n, r in rows.items():
                assert nvar.setdefault(n, r["nvar"]) == r["nvar"], (n, c, nvar[n], r["nvar"])

    k = len(configs)
    T = ["% GENERATED by benchmarks/tables/tab_scopf_pglib_appendix.py -- do not hand-edit.", *LANDSCAPE_REQUIRES, *LANDSCAPE_BEGIN,
         "{\\scriptsize",
         "\\begin{longtable}{lrr" + "rrc" * k + "}",
         "\\caption{" + CAPTION + "}\\label{tab:scopf-pglib-appendix}\\\\"]
    head = ["\\toprule"] + group_header(configs, 3, 3) + [
            "instance & buses & $n_{\\mathrm{var}}$ & " + " & ".join("iter. & fact. & reps" for _ in configs) + " \\\\\\midrule"]
    T += head + ["\\endfirsthead"] + head + ["\\endhead", "\\bottomrule", "\\endfoot"]
    colsum = {c: {"n": 0, "fact": []} for c in configs}
    for n in names:
        cells = []
        for c in configs:
            reps = "".join(letter(data[c][t].get(n), c, cvtol) for t in sorted(data[c]))
            ok, nf, it = majority(data[c], n, c, cvtol)
            if ok:
                cells += [f"{it:.0f}", f"{nf:.0f}", reps]
                colsum[c]["n"] += 1; colsum[c]["fact"].append(nf)
            else:
                cells += [f"\\multicolumn{{2}}{{c}}{{\\textit{{{short(majority_status(data[c], n, c, cvtol))}}}}}", reps]
        T.append(f"{tex_name(n)} & {parts(n)[0]} & {nvar[n]} & " + " & ".join(cells) + " \\\\")
    foot = {}
    for c in configs:
        a = suite_scores(data[c], names, c, cvtol)
        assert len(a["solved"]) == colsum[c]["n"], (c, len(a["solved"]), colsum[c]["n"])
        assert fmt(a["cost"]) == fmt(gm(colsum[c]["fact"]))
        foot[c] = a
        print(f"  {c:<10} solved {len(a['solved'])}/{len(names)} (unguarded {a['n_raw']}), gm fact {a['cost']:.1f}, "
              f"per repetition {sorted(a['per_rep'].items())}")

    def cnt(s):
        return f"{len(s['solved'])}" + (f" ({s['n_raw']})" if s["n_raw"] != len(s["solved"]) else "")
    T.append("\\midrule")
    T.append(f"solved (all {len(names)}) & & & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{cnt(foot[c])}}}" for c in configs) + " \\\\")
    T.append("factorizations (geom.\\ mean) & & & " + " & ".join(f"\\multicolumn{{3}}{{c}}{{{fmt(foot[c]['cost'])}}}" for c in configs) + " \\\\")
    T.append("\\end{longtable}}")
    T += LANDSCAPE_END
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_scopf_pglib_appendix.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
