#!/usr/bin/env python3
"""tab_scopf_all_appendix — the 41 SCOPF instances, one row each (manuscript float tab:scopf-appendix, the appendix
table; the summary over the 41 is tab_gpu_scopf_summary): the 23 reference-network instances and the 18 protocol
instances.

Reads <scopf resdir>/scopf__<config>__<tag>.csv and <scopf_pglib resdir>/scopf_pglib__<config>__<tag>.csv. Rows: the
reference networks, then the protocol networks, K increasing (the order of tab_gpu_scopf_all.load; no separating rule,
removed by Yifan at Overleaf 0eae8ef);
columns: buses and the number of variables, then per configuration one column per repetition (Yifan 2026-11-12: "list
the factorizations (when successful) or failure reason of all three reps"): the factorization count of a repetition
that solves, else the reason for the non-solve as a short italic word (common.rep_cell, common.FAIL_WORD; no
iteration, wall-time or median columns).
LiftedKKT (MadNLP) has no constraint-violation test: its solves count only if the returned point's raw violation
(pr_res) is within the run's constr_viol_tol (post-hoc guard). The footer gives the solved count of every repetition,
computed with the scoring of the other GPU tables (benchmarks/tables/common.suite_scores) and asserted to equal the count
of numeric cells above it, and, as the last row (Yifan 2026-11-12), the cost of tab_gpu_scopf_summary: the geometric mean
over the majority-solved instances of the median factorization count of the succeeding repetitions.

Usage: python3 benchmarks/tables/tab_scopf_all_appendix.py <scopf resdir> <scopf_pglib resdir> [--cvtol=<t>] [--out=<dir>]
         [--provisional=<file>]

--provisional=<file> (the SCOPF rerun, exported before all repetitions are in): <file> lists the instances that carry
fewer repetitions (one name per line); common.PROVISIONAL scoring (an instance is scored by the repetitions it has), the
caption gets tab_gpu_scopf_summary.PROVISIONAL_NOTE and a note on the repetition columns marked $^{*}$ (counted over the
instances that have that repetition), and a missing repetition prints "--". Without the option the output is unchanged.
"""
import statistics, sys
import common
from common import (DEFAULT_OUT, LANDSCAPE_BEGIN, LANDSCAPE_END, LANDSCAPE_REQUIRES, assert_no_tokens, group_header,
                    fmt, gm, rep_cell, success, suite_scores, write)
from tab_gpu_scopf_all import buses, load, tex
from tab_gpu_scopf_summary import provisional_caption

# Caption: the manuscript's (Yifan, Overleaf 0eae8ef; "SCOPF" abbreviated 2026-11-13), verbatim (captions are Yifan's).
CAPTION = ("Detailed results of the solvers on all 41 SCOPF problems formulated as MPCCs. "
           "For each repetition, we report either the number of factorizations needed for the successful solve, or the "
           "reason for the non-solve.")


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 2:
        print(__doc__); return 2
    configs, data, names, cvtol, ref = load(pos[0], pos[1], opt)
    tags = sorted({t for c in configs for t in data[c]})
    assert all(sorted(data[c]) == tags for c in configs), {c: sorted(data[c]) for c in configs}
    nvar = {}
    for c in configs:
        for rows in data[c].values():
            for n, r in rows.items():
                assert nvar.setdefault(n, r["nvar"]) == r["nvar"], (n, c, nvar[n], r["nvar"])

    caption, labels = CAPTION, [str(i + 1) for i in range(len(tags))]
    if "provisional" in opt:
        common.PROVISIONAL = True
        caption, labels = provisional_caption(caption, opt["provisional"], data, configs, tags, names)
    k, m = len(configs), len(tags)
    T = ["% GENERATED by benchmarks/tables/tab_scopf_all_appendix.py -- do not hand-edit.", *LANDSCAPE_REQUIRES, *LANDSCAPE_BEGIN,
         # \footnotesize, \tabcolsep 2.5pt (the largest size that fits both appendix tables on the landscape text width,
         # 650.4pt: PGLIB 620.6pt, SCOPF 636.6pt; at 3pt the SCOPF table is 4.2pt too wide)
         "{\\footnotesize\\setlength{\\tabcolsep}{2.5pt}",
         "\\begin{longtable}{lrr" + "r" * (m * k) + "}",
         "\\caption{" + caption + "}\\label{tab:scopf-appendix}\\\\"]
    head = ["\\toprule"] + group_header(configs, m, 3) + [
            "instance & buses & $n_{\\mathrm{var}}$ & " + " & ".join(" & ".join(labels) for _ in configs)
            + " \\\\\\midrule"]
    T += head + ["\\endfirsthead"] + head + ["\\endhead", "\\bottomrule", "\\endfoot"]
    nsol = {(c, t): 0 for c in configs for t in tags}
    for n in names:
        cells = []
        for c in configs:
            for t in tags:
                x = rep_cell(data[c][t].get(n), c, cvtol)
                nsol[(c, t)] += x.isdigit()
                cells.append(x)
        T.append(f"{tex(n)} & {buses(n)} & {nvar[n]} & " + " & ".join(cells) + " \\\\")
    cost = {}
    for c in configs:
        a = suite_scores(data[c], names, c, cvtol)
        assert all(a["per_rep"][t][0] == nsol[(c, t)] for t in tags), (c, a["per_rep"], nsol)
        # the cost of tab_gpu_scopf_summary: geometric mean over the majority-solved instances of the median factorization
        # count of the succeeding repetitions (recomputed here from the rows, asserted equal to suite_scores)
        med = [statistics.median(float(data[c][t][n]["nfact"]) for t in tags if success(data[c][t].get(n), c, None, cvtol))
               for n in names if a["majority"][n][0]]
        assert fmt(gm(med)) == fmt(a["cost"]), (c, gm(med), a["cost"])
        cost[c] = a["cost"]
        print(f"  {c:<10} solved per repetition {[nsol[(c, t)] for t in tags]} of {len(names)}, "
              f"majority {len(a['solved'])}, gm fact {a['cost']:.1f}")
    T.append("\\midrule")
    # the footer labels span the 3 identifier columns (a label in the first column alone would widen it)
    T.append(f"\\multicolumn{{3}}{{l}}{{solved (of {len(names)})}} & " + " & ".join(str(nsol[(c, t)]) for c in configs for t in tags) + " \\\\")
    T.append("\\multicolumn{3}{l}{factorizations (geom.\\ mean)} & " + " & ".join(f"\\multicolumn{{{len(tags)}}}{{c}}{{{fmt(cost[c])}}}"
                                                                  for c in configs) + " \\\\")
    T.append("\\end{longtable}}")
    T += LANDSCAPE_END
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_scopf_all_appendix.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
