#!/usr/bin/env python3
"""tab_cutest_ma57 — CUTEst, split by how constrained the problem is (manuscript float tab:cutest).

Reads <resdir>/cutest__<config>__ma57.csv (benchmarks/cutest.jl). Slices, from each row's own counts:
regular (m <= n), m_eq > n, and the other m > n, where m = number of general constraints (two-sided counted
once) and m_eq = number of equality rows. A solve counts when the solver's own test passes and its wall time
is within the cap. Cost = geometric mean of factorizations over the configuration's own solved set (Ipopt
records iterations instead, a lower bound); iterations = geometric mean of interior-point iterations over the
same set, zero-iteration solves excluded.

Usage: python3 benchmarks/tables/tab_cutest.py <resdir> [--cap=3600] [--out=<dir>]
"""
import os, sys
from common import DEFAULT_OUT, NAMES, assert_no_tokens, find, fmt, gm, ordered, read_rows, solved, write

# Caption: the manuscript's (overleaf_upload/tables/tab_cutest_ma57.tex), verbatim (captions are Yifan's).
# TODO(caption, stale items to revise once the new numbers exist):
#   - "1070 instances": the population count of the banked campaign; must equal the instance list run.
#   - "the three augmented-Lagrangian configurations": the table may now carry four (the power-kernel cell).
#   - "thirteen instances ... solve with their extrapolation step alone": a count from the banked runs.
#   - the two \claudegreen{...} spans are pending review in the manuscript.
CAPTION = ("CUTEst, 1070 instances, split by how constrained the problem is. Here $m$ counts the dimension of $c$ "
           "only: variable bounds are excluded, and a two-sided general constraint is counted as one row. "
           "\\protect\\claudegreen{Every configuration factorizes with HSL MA57 at its default pivoting threshold and "
           "with its automatic scaling switched on, under one wall-time limit of 3600\\,s per instance.} A solve counts "
           "as a success when the solver's own termination test passes and its wall time is within budget. Cost is the "
           "geometric mean of factorization counts over each configuration's own solved set, and is undefined where that "
           "set is empty. Ipopt's cost is shown as a lower bound since its factorization counter is not exposed. "
           "\\protect\\claudegreen{Iterations are the geometric mean of interior-point iterations over the same set, "
           "counted across the whole run for the three augmented-Lagrangian configurations; thirteen instances that the "
           "two MadNCL configurations solve with their extrapolation step alone, in zero interior-point iterations, are "
           "left out of their iteration means.}")


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    cap = float(opt.get("cap", "3600"))
    files = find(pos[0], r"cutest__(.+?)__(ma57)\.csv")
    configs = ordered(files)
    data = {c: read_rows(files[c]["ma57"], "name") for c in configs}
    names = sorted(set().union(*[set(d) for d in data.values()])) if data else []
    ref = data[configs[0]]
    def dims(n):
        r = next(d[n] for d in data.values() if n in d and int(d[n]["nvar"]) >= 0)
        return int(r["nvar"]), int(r["ncon"]), int(r["n_eq"])
    reg = [n for n in names if dims(n)[1] <= dims(n)[0]]
    neq = [n for n in names if dims(n)[2] > dims(n)[0]]
    rest = [n for n in names if dims(n)[1] > dims(n)[0] and dims(n)[2] <= dims(n)[0]]
    slices = [("all", names), ("regular", reg), ("$m_{\\mathrm{eq}}>n$", neq), ("other $m>n$", rest)]
    cells = {}
    for c in configs:
        d = data[c]
        cells[c] = []
        for _, pop in slices:
            ok = [n for n in pop if solved(d.get(n), cap)]
            cells[c].append((len(ok), gm([float(d[n]["nfact"]) for n in ok]),
                             gm([float(d[n]["iter"]) for n in ok if float(d[n]["iter"]) > 0])))
        print(f"  {c:<10}" + "".join(f"  {s:>5} {g:>7.1f} {i:>7.1f}" for s, g, i in cells[c]))
    T = ["% GENERATED by benchmarks/tables/tab_cutest.py -- do not hand-edit.", "% REQUIRES: booktabs",
         "\\begin{table}[t]\\centering", "\\caption{" + CAPTION + "}", "\\label{tab:cutest}",
         "\\begin{tabular}{lrrrr}\\toprule",
         "configuration & " + " & ".join(l for l, _ in slices) + " \\\\",
         " & " + " & ".join(f"({len(p)})" for _, p in slices) + " \\\\\\midrule",
         "\\multicolumn{5}{l}{\\emph{instances solved}}\\\\"]
    T += [f"{NAMES.get(c, c)} & " + " & ".join(str(s) for s, _, _ in cells[c]) + " \\\\" for c in configs]
    T += ["\\\\[-6pt]", "\\multicolumn{5}{l}{\\emph{cost: geometric mean of factorizations over the solved set}}\\\\"]
    T += [f"{NAMES.get(c, c)} & " + " & ".join(("$\\geq$~" if c == "ipopt" and g == g else "") + fmt(g)
                                                for _, g, _ in cells[c]) + " \\\\" for c in configs]
    T += ["\\\\[-6pt]", "\\multicolumn{5}{l}{\\emph{geometric mean of iterations over the solved set}}\\\\"]
    T += [f"{NAMES.get(c, c)} & " + " & ".join(fmt(i) for _, _, i in cells[c]) + " \\\\" for c in configs]
    T += ["\\bottomrule\\end{tabular}\\end{table}"]
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_cutest_ma57.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
