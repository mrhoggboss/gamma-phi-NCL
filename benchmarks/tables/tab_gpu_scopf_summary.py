#!/usr/bin/env python3
"""tab_gpu_scopf_summary — the 41 SCOPF instances, summary table (manuscript float tab:gpu-scopf), laid out exactly as
tab_gpu_opf: per configuration the solved count of every repetition over the 41 instances, the per-instance majority
over the repetitions, and the geometric mean over the majority-solved set of the median factorization count of the
succeeding repetitions. The 41 are the 23 reference-list instances and the 18 protocol instances (the per-instance rows
are the appendix table, tab_scopf_all_appendix). LiftedKKT (MadNLP) has no constraint-violation test: its successes count
only if the returned point's raw violation (pr_res) is within the runs' constr_viol_tol (post-hoc guard; the unguarded
count in parentheses when it differs).

Usage: python3 benchmarks/tables/tab_gpu_scopf_summary.py <scopf resdir> <scopf_pglib resdir> [--cvtol=<t>] [--out=<dir>]
"""
import sys
from common import DEFAULT_OUT, NAMES, assert_no_tokens, count_cell, fmt, suite_scores, write
from tab_gpu_scopf_all import load   # the merged 23 + 18 result sets, in the row order of the appendix table

# Caption: the manuscript's (Yifan, Overleaf 0eae8ef; "SCOPF" abbreviated 2026-11-13), verbatim (captions are Yifan's);
# "{n}" is the instance count (41).
CAPTION = ("The performance of the solvers on ${n}$ SCOPF instances. Each "
           "repetition is an independent run on the same device. An instance is \\emph{{solved}} when the majority of its "
           "three repetitions solve, and the cost is the geometric mean over that set of the median factorization count of "
           "the succeeding repetitions.")


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 2:
        print(__doc__); return 2
    configs, data, names, cvtol, ref = load(pos[0], pos[1], opt)
    tags = sorted({t for c in configs for t in data[c]})
    if len(tags) != 3:
        print(f"  NOTE: {len(tags)} repetitions in the results; the caption says three")
    T = ["% GENERATED by benchmarks/tables/tab_gpu_scopf_summary.py -- do not hand-edit.", "% REQUIRES: booktabs",
         "\\begin{table}[hbp]\\centering", "\\caption{" + CAPTION.format(n=len(names)) + "}", "\\label{tab:gpu-scopf}",
         "\\begin{tabular}{l" + "r" * (len(tags) + 2) + "}\\toprule",
         f" & \\multicolumn{{{len(tags)}}}{{c}}{{repetition}} & & \\\\",
         f"\\cmidrule(lr){{2-{len(tags) + 1}}}",
         "configuration & " + " & ".join(str(i + 1) for i in range(len(tags))) + " & solved & factorizations \\\\\\midrule"]
    print(f"  {len(names)} instances ({len(ref)} reference-list + {len(names) - len(ref)} protocol)")
    for c in configs:
        sc = suite_scores(data[c], names, c, cvtol)
        per = [count_cell(*sc["per_rep"][t], c) if t in sc["per_rep"] else "--" for t in tags]
        nmaj = len(sc["solved"])
        mcell = f"\\textbf{{{nmaj}}}" + (f" ({sc['n_raw']})" if sc["n_raw"] != nmaj else "")
        T.append(f"{NAMES.get(c, c)} & " + " & ".join(str(x) for x in per) + f" & {mcell} & {fmt(sc['cost'])} \\\\")
        print(f"  {c:<10} reps={per} majority={nmaj} (unguarded {sc['n_raw']})/{len(names)} gm(median nfact)={sc['cost']:.1f}")
    T.append("\\bottomrule\\end{tabular}\\end{table}")
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_gpu_scopf_summary.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
