#!/usr/bin/env python3
"""fig_gpu_scaling + tab_gpu_ladder — GPU scaling on the COPS size ladder (manuscript floats fig:cops and
tab:cops-ladder). Port of the research harness's emitter: pgfplots group plot, x = nvar, y = factorizations
(log-log), one panel per family in alphabetical order, non-solves marked by kind on a band below the solves;
the appendix table lists every rung with the factorization count or the kind of non-solve.

Reads <resdir>/cops_ladder__<config>__<tag>.csv (benchmarks/gpu.jl, columns family, size, nvar, status, nfact).
LiftedKKT (MadNLP) has no constraint-violation test: a LiftedKKT solve whose returned point violates the
constraints by more than the run's constr_viol_tol (pr_res) is drawn as a non-solve of kind "violation".

Usage: python3 benchmarks/tables/fig_gpu_scaling.py <resdir> [--tag=r1] [--cvtol=<t>] [--out=<dir>]
Requires in the document preamble: \\usepackage{pgfplots} and \\usepgfplotslibrary{groupplots}.
"""
import os, sys
from collections import OrderedDict
from common import DEFAULT_OUT, GUARDED, NAMES, assert_no_tokens, find, ordered, read_cvtol, read_rows, violation, write

PANELS = ["bearing", "catmix", "channel", "elec", "gasoil", "marine",
          "minsurf", "pinene", "polygon", "robot", "steering", "torsion"]
SUCC = "SOLVE_SUCCEEDED"
KIND = OrderedDict([
    ("MAXIMUM_ITERATIONS_EXCEEDED", ("iteration limit", "x", "mark size=3.5pt")),
    ("INFEASIBLE_PROBLEM_DETECTED", ("infeasible", "square", "mark size=2.5pt")),
    ("SOLVED_TO_ACCEPTABLE_LEVEL", ("acceptable", "triangle", "mark size=3pt")),
    ("MAXIMUM_WALLTIME_EXCEEDED", ("wall-time limit", "diamond", "mark size=3pt")),
    ("BUILD_FAILED", ("did not build", "otimes", "mark size=3pt")),
    ("VIOLATION", ("violation", "pentagon", "mark size=3pt")),
])
COLORS = ["black", "blue!70!black", "red!70!black", "orange!80!black", "green!50!black"]
# Captions: the manuscript's (overleaf_upload/tables/fig_gpu_scaling.tex, tab_gpu_ladder.tex), verbatim (Yifan's).
# TODO(caption, stale items to revise once the new numbers exist):
#   - "four configurations": the harness can plot five (the power-kernel cell); the count must match the run.
#   - "one run per cell": true for a single tag; say so if repetitions are added.
FIG_CAPTION = ("GPU scaling on the COPS size ladder: factorization count against problem size, all twelve laddered "
               "families in alphabetical order, four configurations, one run per cell. Filled circles are solves. "
               "Open markers on the lower band are \\emph{non-solves}, distinguished by failure status.")
TAB_CAPTION = ("Full problem and solve statistics for the GPU scaling study in Section~\\ref{sec:results:scaling}, for all "
               "twelve COPS problem families. Entries are factorization counts for solves; non-solves are shown by kind.")


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    tag = opt.get("tag", "r1")
    files = find(pos[0], r"cops_ladder__(.+?)__(.+?)\.csv")
    configs = [c for c in ordered(files) if tag in files[c]]
    cvtol = read_cvtol(pos[0], opt)
    data = []
    for c in configs:
        rows = read_rows(files[c][tag], "instance")
        d = {}
        for r in rows.values():
            r = dict(r)
            if c in GUARDED and r["status"] == SUCC and not violation(r) <= cvtol:
                r["status"] = "VIOLATION"     # post-hoc guard: a solve whose point violates the constraints
            d[(r["family"], r["size"])] = r
        data.append((NAMES.get(c, c), d))
    L = ["% GENERATED by benchmarks/tables/fig_gpu_scaling.py -- do not hand-edit.",
         "% REQUIRES: \\usepackage{pgfplots} and \\usepgfplotslibrary{groupplots}",
         "\\begin{figure}[t]\\centering", "\\begin{tikzpicture}",
         "\\begin{groupplot}[group style={group size=4 by 3, horizontal sep=0.95cm,",
         "    vertical sep=1.25cm, ylabels at=edge left, xlabels at=edge bottom},",
         "    width=4.35cm, height=4.1cm, xmode=log, ymode=log,",
         "    xlabel={$n_{\\mathrm{var}}$}, ylabel={factorizations},",
         "    tick label style={font=\\tiny}, label style={font=\\scriptsize}, title style={font=\\scriptsize},",
         "    axis background/.style={fill=black!6}, axis line style={black!45},",
         "    tick style={black!45}, grid=both, major grid style={white, line width=0.7pt},",
         "    minor grid style={white, line width=0.35pt},",
         "    yticklabel={\\pgfmathparse{exp(\\tick)}\\pgfmathprintnumber[fixed, precision=0,",
         "        1000 sep={\\,}]{\\pgfmathresult}},",
         "    legend style={font=\\scriptsize}]"]
    drawn = set()
    for pi, fam in enumerate(PANELS):
        o = f"title={{\\texttt{{{fam}}}}}"
        if pi == 0:
            o += (", legend to name=copslegend, legend columns=4,"
                  " legend style={draw=none, column sep=1.4ex, font=\\scriptsize}")
        L.append(f"\\nextgroupplot[{o}]")
        vals = [float(r["nfact"]) for _, d in data for (f, s), r in d.items()
                if f == fam and r["status"] == SUCC and float(r["nfact"]) > 0]
        floor = (min(vals) / 3.0) if vals else 1.0
        for ai, ((lbl, d), col) in enumerate(zip(data, COLORS)):
            band = floor * (1.0 - 0.13 * ai)
            pts = sorted(((int(r["nvar"]), float(r["nfact"])) for (f, s), r in d.items()
                          if f == fam and r["status"] == SUCC and int(r["nvar"]) > 0))
            if pts:
                L.append(f"\\addplot[color={col}, mark=*, mark size=1.6pt, thick] coordinates {{"
                         + " ".join(f"({x},{y:g})" for x, y in pts) + "};")
            if pi == 0:
                if not pts:
                    L.append(f"\\addlegendimage{{color={col}, mark=*, mark size=1.6pt, thick}}")
                L.append(f"\\addlegendentry{{{lbl}}}")
            for st, (name, mk, msz) in KIND.items():
                bad = sorted(int(r["nvar"]) for (f, s), r in d.items()
                             if f == fam and r["status"].startswith(st) and int(r["nvar"]) > 0)
                if bad:
                    drawn.add(st)
                    L.append(f"\\addplot[color={col}, mark={mk}, {msz}, only marks, forget plot] coordinates {{"
                             + " ".join(f"({x},{band:g})" for x in bad) + "};")
    L += ["\\end{groupplot}", "\\end{tikzpicture}", "\\par\\vspace{3pt}", "\\ref{copslegend}", "\\par\\vspace{1pt}"]
    keys = [("*", "mark size=1.6pt", "solve")] + [(mk, msz, nm) for st, (nm, mk, msz) in KIND.items() if st in drawn]
    L.append("{\\scriptsize " + "\\quad ".join(
        f"\\tikz[baseline=-0.55ex]{{\\draw[black] plot[mark={mk}, {msz}] coordinates {{(0,0)}};}}~{nm}"
        for mk, msz, nm in keys) + "}")
    L += ["\\caption{" + FIG_CAPTION + "}", "\\label{fig:cops}", "\\end{figure}"]
    assert_no_tokens("\n".join(L))
    out = opt.get("out", DEFAULT_OUT)
    write(out, "fig_gpu_scaling.tex", L)

    T = ["% GENERATED by benchmarks/tables/fig_gpu_scaling.py -- do not hand-edit.", "% REQUIRES: booktabs",
         "\\begin{table}[t]\\centering\\footnotesize\\setlength{\\tabcolsep}{3pt}",
         "\\caption{" + TAB_CAPTION + "}", "\\label{tab:cops-ladder}",
         "\\begin{tabular}{llr" + "r" * len(data) + "}\\toprule",
         "family & size & $n_{\\mathrm{var}}$ & " + " & ".join(l for l, _ in data) + " \\\\\\midrule"]
    keys = sorted({k for _, d in data for k in d}, key=lambda k: (k[0], int(next(d[k]["nvar"] for _, d in data if k in d))))
    for fam in PANELS:
        rungs = [k for k in keys if k[0] == fam]
        for i, k in enumerate(rungs):
            nv = int(next(d[k]["nvar"] for _, d in data if k in d))
            cells = []
            for _, d in data:
                r = d.get(k)
                if r is None:
                    cells.append("--")
                elif r["status"] == SUCC:
                    cells.append(r["nfact"])
                else:
                    kind = next((v[0] for s, v in KIND.items() if r["status"].startswith(s)), r["status"].lower())
                    cells.append("\\textit{" + kind.replace("_", "\\_") + "}")
            T.append((f"\\texttt{{{fam}}}" if i == 0 else "") + f" & {k[1]} & {nv:,} & " + " & ".join(cells) + " \\\\")
        if rungs:
            T.append("\\addlinespace")
    T.append("\\bottomrule\\end{tabular}\\end{table}")
    assert_no_tokens("\n".join(T))
    write(out, "tab_gpu_ladder.tex", T)
    for lbl, d in data:
        print(f"  {lbl:<40} solved {sum(1 for r in d.values() if r['status'] == SUCC)}/{len(d)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
