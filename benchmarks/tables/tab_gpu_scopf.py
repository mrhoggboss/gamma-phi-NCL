#!/usr/bin/env python3
"""tab_gpu_scopf — the 23 reference-network instances, per instance: a table of earlier manuscript versions, NOT a float and
not emitted (an unreported extra, runnable by hand; its tt() is common.scopf_ref_tex, which the reported SCOPF floats
use); it writes tab:gpu-scopf, never \\input it.

Reads <resdir>/scopf__<config>__<tag>.csv (benchmarks/gpu.jl). With one repetition, each cell is the solve's
interior-point iteration count and factorization count; with several, a configuration solves an instance
when the majority of its repetitions do, and the cell shows the medians over the succeeding repetitions.
A dash is a non-solve. Footer: solved count and the geometric mean of factorizations over the solved set.
LiftedKKT (MadNLP) has no constraint-violation test: its solves count only if the returned point's raw
violation (pr_res) is within the run's constr_viol_tol (post-hoc guard; the unguarded count in parentheses).

Usage: python3 benchmarks/tables/tab_gpu_scopf.py <resdir> [--cvtol=<t>] [--out=<dir>]
"""
import sys
from common import (DEFAULT_OUT, assert_no_tokens, find, fmt, gm, group_header, majority, ordered, read_cvtol, read_rows,
                    scopf_ref_tex, write)

# Unreported extra (an earlier manuscript layout); not a float, no caption will be written.
CAPTION = ("The security-constrained complementarity problems, per instance, one pass each. For each solve, the entry "
           "is the interior-point iteration count and the factorization count; a dash is a non-solve, and every "
           "non-solve in this table is the iteration limit reached at 3000, so no number is reported for it.")


tt = scopf_ref_tex   # the short instance name (common.scopf_ref_tex)


def main(argv):
    pos = [a for a in argv if not a.startswith("--")]
    opt = dict(a[2:].split("=", 1) for a in argv if a.startswith("--") and "=" in a)
    if len(pos) != 1:
        print(__doc__); return 2
    files = find(pos[0], r"scopf__(.+?)__(.+?)\.csv")
    configs = ordered(files)
    cvtol = read_cvtol(pos[0], opt)
    data = {c: {t: read_rows(files[c][t], "instance") for t in files[c]} for c in configs}
    names = []
    for c in configs:
        for rows in data[c].values():
            for n in rows:
                n in names or names.append(n)
    k = len(configs)
    T = ["% GENERATED by benchmarks/tables/tab_gpu_scopf.py -- do not hand-edit.", "% REQUIRES: booktabs",
         "\\begin{table}[tbp]\\centering\\small\\setlength{\\tabcolsep}{3pt}", "\\caption{" + CAPTION + "}", "\\label{tab:gpu-scopf}",
         "\\begin{tabular}{l" + "rr" * k + "}\\toprule"] + group_header(configs, 2, 1) + [
         "instance & " + " & ".join("iter.\\ & fact." for _ in configs) + " \\\\\\midrule"]
    summ = {c: [] for c in configs}
    raw = {c: sum(1 for n in names if majority(data[c], n)[0]) for c in configs}
    for n in names:
        cells = []
        for c in configs:
            ok, nf, it = majority(data[c], n, c, cvtol)
            if ok:
                summ[c].append(nf)
                cells += [f"{it:.0f}", f"{nf:.0f}"]
            else:
                cells += ["---", "---"]
        T.append(f"{tt(n)} & " + " & ".join(cells) + " \\\\")
    T.append("\\midrule solved & " + " & ".join(
        f"\\multicolumn{{2}}{{c}}{{{len(summ[c])}/{len(names)}" + (f" ({raw[c]})" if raw[c] != len(summ[c]) else "") + "}"
        for c in configs) + " \\\\")
    T.append("factorizations (geom.\\ mean) & " + " & ".join(f"\\multicolumn{{2}}{{c}}{{{fmt(gm(summ[c]))}}}" for c in configs) + " \\\\")
    T.append("\\bottomrule\\end{tabular}\\end{table}")
    for c in configs:
        print(f"  {c:<10} solved {len(summ[c])}/{len(names)} (unguarded {raw[c]})  gm fact {gm(summ[c]):.1f}  reps {sorted(data[c])}")
    assert_no_tokens("\n".join(T))
    write(opt.get("out", DEFAULT_OUT), "tab_gpu_scopf.tex", T)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
